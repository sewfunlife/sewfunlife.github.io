#!/usr/bin/env node
// scripts/optimize-images.mjs
//
// Converts every source PNG/JPG under `_source/` into a web-optimised WebP
// under `public/work/`, and emits a manifest at `content/images.json`.
//
// Usage: node scripts/optimize-images.mjs   (or `npm run images`)
//
// ---------------------------------------------------------------------------
// TEMPLATE USAGE
// ---------------------------------------------------------------------------
// 1. Where source images go
//    Drop full-resolution artwork into `_source/`. You can either:
//      - dump files loosely at the top level of `_source/` (these become
//        "deck" plates), or
//      - put them inside a subfolder (any depth) whose name starts with a
//        two-digit number, to control which *category* they land in:
//          01_... -> "mood"   (moodboard / concept images)
//          02_... -> "app"    (applications / mock-up presentations)
//          03_... -> "mood"   (menus, brochures, etc. — see PIZZERIA/
//                              REAL_ESTATE special-cases below)
//          04_... -> "cover"  (hero / campaign artwork)
//        Folder name and nesting beyond the leading "NN_" is up to you
//        (e.g. `_source/01_Moodboard_Images/` or a more deeply nested path
//        like `_source/MyDrop/01_Moodboard_Images/` both work).
//
// 2. Filename convention: `PROJECT_NN_Description.png`
//      - `PROJECT`     one or more `_`-joined, ALL-CAPS words identifying the
//                      project. Becomes the output slug, lowercased with
//                      underscores turned into hyphens (`MY_BRAND` -> `my-brand`).
//      - `NN`          a 1-3 digit run number. Controls sort order and is the
//                      first half of the manifest `key` (zero-padded to 2
//                      digits, e.g. `05`).
//      - `Description`  everything after NN. Becomes both the slugified
//                      second half of the manifest `key` and the human-
//                      readable `label` for the plate.
//    If a filename has no numeric segment at all (e.g. `MY_BRAND_Cover.png`),
//    the script falls back to treating every leading ALL-CAPS word as the
//    project prefix, `NN` as `01`, and everything after as the description.
//    If no project prefix can be determined at all, the file still gets
//    processed under a `studio` slug rather than being skipped.
//
// 3. Redirecting a derived slug: `PREFIX_ALIASES` below
//    Sometimes you want several filename prefixes to collapse into one
//    project (e.g. `REAL_ESTATE_OPEN_HOUSE_*` and `REAL_ESTATE_BROCHURE_A_*`
//    should both live under the single `real-estate` project). Add an entry
//    to `PREFIX_ALIASES` for that — you do NOT have to add anything here for
//    the common case where the derived slug is already what you want.
//
// 4. `content/images.json` is fully regenerated by this script. The `key`
//    field it writes for each plate (`<nn>-<description-slug>`, e.g.
//    `05-billboard`) is what `content/projects.json`'s `plates[].key` must
//    match for that plate to pick up a caption/title in the UI. If you
//    rename a source file, update the matching `plates[].key` too.
// ---------------------------------------------------------------------------

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const SOURCE_ROOT = path.join(ROOT, '_source');
const OUTPUT_ROOT = path.join(ROOT, 'public', 'work');
const MANIFEST_PATH = path.join(ROOT, 'content', 'images.json');

const WEBP_OPTIONS = { quality: 80, effort: 5 };
const MAX_EDGE = 1600;
const IMAGE_EXT_RE = /\.(png|jpe?g)$/i;

// Small responsive variant: same quality settings as the full-size WebP, but
// capped at this longest edge. Filename is the full-size filename with
// `-800` inserted before the extension. Skipped entirely (no file, no
// manifest fields) when the full-size output is already at or under this,
// since that would just be a same-size duplicate of the full image.
const SMALL_MAX_EDGE = 800;
const SMALL_SUFFIX = '-800';

// ---------------------------------------------------------------------------
// PREFIX_ALIASES — optional overrides for the automatically-derived project
// slug (see step 3 above). Keys are the slug the naming convention would
// derive on its own; values are the slug you actually want it to land under.
// Add your own entries here as needed — most template users won't need any.
//
// This project needs the four below because several filename prefixes are
// meant to share one project folder.
// ---------------------------------------------------------------------------
const PREFIX_ALIASES = {
  'pizzeria-presentation': 'pizzeria',
  'real-estate-open-house': 'real-estate',
  'real-estate-brochure-a': 'real-estate',
  'real-estate-brochure-b': 'real-estate',
};

// ---------------------------------------------------------------------------
// CATEGORY_OVERRIDES — optional per-prefix category overrides, for the rare
// case where a specific filename prefix should land in a different category
// than its source folder's default (see BULK category table above). Matched
// against the *derived* (pre-alias) prefix, e.g. `PIZZERIA_PRESENTATION`.
//
// This project needs these because the presentation/brochure mock-ups are
// "app" (application) plates that happen to live in the same source folder
// as the "mood" images for their project.
// ---------------------------------------------------------------------------
const CATEGORY_OVERRIDES = [
  { prefix: 'PIZZERIA_PRESENTATION', category: 'app' },
  { prefix: 'REAL_ESTATE_BROCHURE_A', category: 'app' },
  { prefix: 'REAL_ESTATE_BROCHURE_B', category: 'app' },
];

// Numbered-subfolder name prefix -> default category for files inside it.
const CATEGORY_BY_DIR_PREFIX = {
  '01': 'mood',
  '02': 'app',
  '03': 'mood',
  '04': 'cover',
};


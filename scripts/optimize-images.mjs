// ---------------------------------------------------------------------------
// Filename parsing (the `PROJECT_NN_Description` convention from the usage
// block above).
// ---------------------------------------------------------------------------

function slugify(s) {
  return s
    .toLowerCase()
    .replace(/_/g, '-')
    .replace(/[^a-z0-9-]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

// A segment counts as part of the ALL-CAPS project prefix if it contains at
// least one letter and is already fully uppercase (so a bare numeric segment
// never matches here — that's handled by the digit-scan below instead).
function isAllCapsSegment(seg) {
  return /[A-Za-z]/.test(seg) && seg === seg.toUpperCase();
}

// `SOFIA_09_Urban_Portrait` -> { rawPrefix: 'SOFIA', nn: '09', descriptorRaw: 'Urban_Portrait', ... }
// `WITHOUT_ME_Original_Cover` (no numeric segment) -> { rawPrefix: 'WITHOUT_ME', nn: '01', descriptorRaw: 'Original_Cover', ... }
function deriveParts(baseName) {
  const segments = baseName.split('_').filter(Boolean);
  const digitIdx = segments.findIndex((s) => /^\d{1,3}$/.test(s));

  let prefixSegs;
  let nn;
  let descriptorSegs;

  if (digitIdx !== -1) {
    prefixSegs = segments.slice(0, digitIdx);
    nn = segments[digitIdx].padStart(2, '0');
    descriptorSegs = segments.slice(digitIdx + 1);
  } else {
    let i = 0;
    while (i < segments.length && isAllCapsSegment(segments[i])) i += 1;
    prefixSegs = segments.slice(0, i);
    nn = '01';
    descriptorSegs = segments.slice(i);
  }

  const rawPrefix = prefixSegs.join('_');
  const descriptorRaw = descriptorSegs.join('_') || baseName;
  const label = descriptorRaw.replace(/_/g, ' ');
  const nameSlug = slugify(descriptorRaw);

  return { rawPrefix, nn, nameSlug, label };
}

// Applies PREFIX_ALIASES, falling back to a `studio` slug when no project
// prefix could be determined at all (rather than throwing).
function resolveSlug(rawPrefix, sourcePath) {
  if (!rawPrefix) {
    console.warn(`  [warn] Could not determine a project prefix for "${path.basename(sourcePath)}" — using slug "studio".`);
    return 'studio';
  }
  const derived = slugify(rawPrefix);
  return PREFIX_ALIASES[derived] ?? derived;
}

function categoryOverrideFor(rawPrefix, defaultCategory) {
  const hit = CATEGORY_OVERRIDES.find((o) => rawPrefix === o.prefix || rawPrefix.startsWith(o.prefix + '_'));
  return hit ? hit.category : defaultCategory;
}

// ---------------------------------------------------------------------------
// Conversion
// ---------------------------------------------------------------------------

async function dominantColorHex(image) {
  const { data } = await image
    .clone()
    .removeAlpha()
    .resize(1, 1, { fit: 'fill' })
    .raw()
    .toBuffer({ resolveWithObject: true });
  const [r, g, b] = data;
  return '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');
}

// Full-size filename -> small-variant filename, by inserting SMALL_SUFFIX
// before the extension (`foo.webp` -> `foo-800.webp`).
function smallVariantPath(outPath) {
  const ext = path.extname(outPath);
  return `${outPath.slice(0, -ext.length)}${SMALL_SUFFIX}${ext}`;
}

async function convertOne(sourcePath, outPath) {
  await fs.mkdir(path.dirname(outPath), { recursive: true });
  const image = sharp(sourcePath);
  const dom = await dominantColorHex(image);
  const info = await image
    .clone()
    .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: 'inside', withoutEnlargement: true })
    .webp(WEBP_OPTIONS)
    .toFile(outPath);

  let small = null;
  if (Math.max(info.width, info.height) > SMALL_MAX_EDGE) {
    const smallOutPath = smallVariantPath(outPath);
    const smallInfo = await image
      .clone()
      .resize({ width: SMALL_MAX_EDGE, height: SMALL_MAX_EDGE, fit: 'inside', withoutEnlargement: true })
      .webp(WEBP_OPTIONS)
      .toFile(smallOutPath);
    small = { src: smallOutPath, w: smallInfo.width, h: smallInfo.height };
  }

  return { w: info.width, h: info.height, dom, small };
}

// ---------------------------------------------------------------------------
// Job collection
// ---------------------------------------------------------------------------

// Recursively finds every directory under `dir` whose name starts with a
// known "NN_" category prefix (01/02/03/04 — see CATEGORY_BY_DIR_PREFIX).
// Nesting above the matched directory is unconstrained, so both a shallow
// `_source/01_Foo/` and a deeply-nested drop folder work the same way.
async function findCategoryDirs(dir) {
  const results = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return results;
  }
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const abs = path.join(dir, entry.name);
    const m = entry.name.match(/^(\d{2})_/);
    if (m && CATEGORY_BY_DIR_PREFIX[m[1]]) {
      results.push({ absDir: abs, category: CATEGORY_BY_DIR_PREFIX[m[1]] });
      continue; // treat matched dirs as leaves; don't also scan inside them
    }
    results.push(...(await findCategoryDirs(abs)));
  }
  return results;
}

async function collectBulkJobs() {
  const jobs = [];
  const categoryDirs = (await findCategoryDirs(SOURCE_ROOT)).sort((a, b) => a.absDir.localeCompare(b.absDir));

  for (const { absDir, category: defaultCategory } of categoryDirs) {
    const entries = await fs.readdir(absDir);
    const images = entries.filter((f) => IMAGE_EXT_RE.test(f)).sort();
    for (const file of images) {
      const baseName = file.replace(IMAGE_EXT_RE, '');
      const { rawPrefix, nn, nameSlug, label } = deriveParts(baseName);
      const sourcePath = path.join(absDir, file);
      const slug = resolveSlug(rawPrefix, sourcePath);
      const category = categoryOverrideFor(rawPrefix, defaultCategory);
      jobs.push({ sourcePath, slug, category, nn, nameSlug, label });
    }
  }
  return jobs;
}

async function collectDeckJobs() {
  const jobs = [];
  let entries;
  try {
    entries = await fs.readdir(SOURCE_ROOT, { withFileTypes: true });
  } catch {
    return jobs;
  }
  const files = entries.filter((e) => e.isFile() && IMAGE_EXT_RE.test(e.name)).map((e) => e.name).sort();

  for (const file of files) {
    const override = DECK_SLIDES_BY_FILE.get(file);
    if (override) {
      jobs.push({
        sourcePath: path.join(SOURCE_ROOT, file),
        slug: override.slug,
        category: 'deck',
        nn: override.nn,
        nameSlug: override.descriptor,
        label: override.label,
      });
      continue;
    }

    // Not in the explicit override table — derive it from the filename like
    // any other source image. Never throws: worst case is a `studio` slug.
    const baseName = file.replace(IMAGE_EXT_RE, '');
    const { rawPrefix, nn, nameSlug, label } = deriveParts(baseName);
    const sourcePath = path.join(SOURCE_ROOT, file);
    const slug = resolveSlug(rawPrefix, sourcePath);
    console.warn(`  [warn] "${file}" is not in DECK_SLIDES — derived slug "${slug}", key "${nn}-${nameSlug}".`);
    jobs.push({ sourcePath, slug, category: 'deck', nn, nameSlug, label });
  }
  return jobs;
}

async function main() {
  try {
    await fs.access(SOURCE_ROOT);
  } catch {
    console.log(`No "_source/" directory found at ${SOURCE_ROOT} — nothing to do.`);
    return;
  }

  const jobs = [...(await collectBulkJobs()), ...(await collectDeckJobs())];
  if (jobs.length === 0) {
    console.log('No source images found under "_source/" — nothing to do.');
    return;
  }
  console.log(`Found ${jobs.length} source images to convert.`);

  const manifest = {};
  const seenOutputs = new Set();
  let processed = 0;
  const failures = [];

  for (const job of jobs) {
    const filename = `${job.category}-${job.nn}-${job.nameSlug}.webp`;
    const outPath = path.join(OUTPUT_ROOT, job.slug, filename);
    const webSrc = `/work/${job.slug}/${filename}`;

    if (seenOutputs.has(outPath)) {
      failures.push({ file: job.sourcePath, error: `Duplicate output path: ${outPath}` });
      continue;
    }
    seenOutputs.add(outPath);

    try {
      const { w, h, dom, small } = await convertOne(job.sourcePath, outPath);

      const entry = {
        src: webSrc,
        w,
        h,
        key: `${job.nn}-${job.nameSlug}`,
        label: job.label,
        dom,
      };
      if (small) {
        entry.sm = webSrc.replace(/\.webp$/, `${SMALL_SUFFIX}.webp`);
        entry.smW = small.w;
      }

      manifest[job.slug] ??= {};
      manifest[job.slug][job.category] ??= [];
      manifest[job.slug][job.category].push(entry);

      processed += 1;
      process.stdout.write(`\r  converted ${processed}/${jobs.length}`);
    } catch (err) {
      failures.push({ file: job.sourcePath, error: err.message });
    }
  }
  process.stdout.write('\n');

  // Sort each category array ascending by key, drop nothing (emptiness is
  // handled naturally since arrays are only created when a job lands in them).
  for (const slug of Object.keys(manifest)) {
    for (const category of Object.keys(manifest[slug])) {
      manifest[slug][category].sort((a, b) => a.key.localeCompare(b.key));
    }
  }

  await fs.mkdir(path.dirname(MANIFEST_PATH), { recursive: true });
  await fs.writeFile(MANIFEST_PATH, JSON.stringify(manifest, null, 2) + '\n');

  console.log(`Wrote manifest: ${MANIFEST_PATH}`);
  console.log(`Processed ${processed} images (${failures.length} failures).`);
  if (failures.length) {
    console.error('Failures:');
    for (const f of failures) console.error(`  ${f.file}: ${f.error}`);
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
